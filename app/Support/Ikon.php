    public static function svg(string $nama): string
    {
        return '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
            .(self::PATH[$nama] ?? self::PATH['bars']).'</svg>';
    }

    
    public static function untuk(string $label): string
    {
        return match (true) {
            (bool) preg_match('/kendaraan|dipakai|tersedia/i', $label)  => 'truck',
            (bool) preg_match('/driver|pengemudi/i', $label)            => 'user',
            (bool) preg_match('/seksi/i', $label)                       => 'users',
            (bool) preg_match('/stnk|bpkb|pajak/i', $label)             => 'file',
            (bool) preg_match('/servis|perbaikan/i', $label)            => 'tool',
            (bool) preg_match('/pengajuan|menunggu|persetujuan/i', $label) => 'clock',
            (bool) preg_match('/disetujui|selesai/i', $label)           => 'check',
            default                                                     => 'bars',
        };
    }
